import sharp from 'sharp';
import fs from 'node:fs';
import path from 'node:path';

const root = 'public/assets';
const out = {};
for (const dir of fs.readdirSync(root)) {
  const full = path.join(root, dir);
  if (!fs.statSync(full).isDirectory()) continue;
  for (const f of fs.readdirSync(full)) {
    if (!/\.(jpg|jpeg|png)$/i.test(f)) continue;
    const m = await sharp(path.join(full, f)).metadata();
    out[`/assets/${dir}/${f}`] = { w: m.width, h: m.height };
  }
}
const body = `// Generated by scripts/image-dimensions.mjs — do not edit by hand.
// Explicit width/height on every image prevents cumulative layout shift.

export type Dim = { w: number; h: number };

export const imageDimensions: Record<string, Dim> = ${JSON.stringify(out, null, 2)};

export function dim(src: string): Dim {
  return imageDimensions[src] ?? { w: 1200, h: 800 };
}
`;
fs.writeFileSync('content/image-dimensions.ts', body);
console.log('wrote', Object.keys(out).length, 'entries');
